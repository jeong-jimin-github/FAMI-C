def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mesen", type=Path, help="path to Mesen.exe")
    parser.add_argument("--timeout", type=int, default=15)
    args = parser.parse_args()

    mesen = find_mesen(args.mesen)
    source_path = PROJECT_ROOT / "examples" / "tetris.c"
    source = source_path.read_text(encoding="utf-8")
    assembly = compile_c_to_asm(source)
    assembler = Assembler()
    assembler.assemble(assembly)

    with tempfile.TemporaryDirectory(prefix="famic-mesen-") as temp:
        temp_path = Path(temp)
        rom_path = temp_path / "tetris.nes"
        lua_path = temp_path / "smoke.lua"
        build_rom(source_path, rom_path, None)
        lua_path.write_text(lua_script(assembler.symbols), encoding="utf-8")
        command = [
            str(mesen),
            "--testRunner",
            f"--timeout={args.timeout}",
            "--enableStdout",
            str(lua_path),
            str(rom_path),
        ]
        result = subprocess.run(command, cwd=PROJECT_ROOT, text=True, capture_output=True)

    if result.stdout.strip():
        print(result.stdout.strip())
    if result.stderr.strip():
        print(result.stderr.strip(), file=sys.stderr)
    if result.returncode != 0:
        print(f"Mesen smoke test failed with exit code {result.returncode}", file=sys.stderr)
        return result.returncode or 1
    print("Mesen smoke test passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
