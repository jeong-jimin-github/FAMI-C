def find_mesen(explicit: Path | None) -> Path:
    candidates = []
    if explicit is not None:
        candidates.append(explicit)
    candidates.append(Path.home() / "Downloads" / "Mesen_2.2.1_Windows" / "Mesen.exe")
    for candidate in candidates:
        if candidate.is_file():
            return candidate.resolve()
    raise FileNotFoundError("Mesen.exe not found; pass --mesen PATH")


